#!/usr/bin/env bash
# Starts the Follow Me simulation, optionally with a camera tilted down by N degrees.
#
#   tez/deney/follow_sim/baslat.sh                 # level camera
#   tez/deney/follow_sim/baslat.sh --egim 40       # camera looking 40 deg down
#   HEADLESS=1 tez/deney/follow_sim/baslat.sh --egim 40
#
# Does not touch the PX4 tree: it generates models/x500_egik_kamera (x500 + Camera Module 3 camera mono_cam_cm3,
# pitched down by N deg, 0 = level) and worlds/renkli_duz_egik.sdf (renkli_duz + that drone, named x500_mono_cam_0),
# then lets PX4 attach to the drone already in the world (PX4_GZ_MODEL_NAME). Run kur.sh once before.
set -euo pipefail

SIM_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PX4_DIR="${PX4_DIR:-$(cd "$SIM_DIR/../../.." && pwd)}"   # this folder lives in <Autopilot>/tez/deney/
GZ_DIR="$PX4_DIR/Tools/simulation/gz"
TILT=0

while [[ $# -gt 0 ]]; do
  case "$1" in
    --egim) TILT="$2"; shift 2 ;;
    -h|--help) sed -n '2,10p' "$0"; exit 0 ;;
    *) echo "Bilinmeyen seçenek: $1"; exit 1 ;;
  esac
done

link() {  # link <source> <relative target inside GZ_DIR>, hidden from git status
  local exclude_file
  exclude_file="$(git -C "$GZ_DIR" rev-parse --git-path info/exclude)"
  [[ "$exclude_file" = /* ]] || exclude_file="$GZ_DIR/$exclude_file"
  ln -sfn "$1" "$GZ_DIR/$2"
  grep -qxF "$2" "$exclude_file" 2>/dev/null || echo "$2" >> "$exclude_file"
}

pitch_rad=$(python3 -c "import math; print(f'{math.radians(float(\"$TILT\")):.6f}')")
mkdir -p "$SIM_DIR/models/x500_egik_kamera"
cat > "$SIM_DIR/models/x500_egik_kamera/model.config" <<'EOF'
<?xml version="1.0"?>
<model>
  <name>x500_egik_kamera</name>
  <version>1.0</version>
  <sdf version="1.9">model.sdf</sdf>
  <description>Generated by follow_sim/baslat.sh: x500 with Camera Module 3 camera tilted down</description>
</model>
EOF
cat > "$SIM_DIR/models/x500_egik_kamera/model.sdf" <<EOF
<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by follow_sim/baslat.sh --egim $TILT: x500 + mono_cam_cm3 pitched $TILT deg down. -->
<sdf version='1.9'>
  <model name='x500_egik_kamera'>
    <include merge='true'>
      <uri>model://x500</uri>
    </include>
    <include merge='true'>
      <uri>model://mono_cam_cm3</uri>
      <pose>.12 .03 .242 0 $pitch_rad 0</pose>
    </include>
    <joint name="CameraJoint" type="fixed">
      <parent>base_link</parent>
      <child>camera_link</child>
      <pose relative_to="base_link">.12 .03 .242 0 $pitch_rad 0</pose>
    </joint>
  </model>
</sdf>
EOF
# renkli_duz + the drone (PX4 attaches to it instead of spawning x500_mono_cam)
python3 - "$SIM_DIR/worlds/renkli_duz.sdf" "$SIM_DIR/worlds/renkli_duz_egik.sdf" <<'EOF'
import sys
src, dst = sys.argv[1:3]
text = open(src, encoding="utf-8").read().replace('<world name="renkli_duz">', '<world name="renkli_duz_egik">', 1)
drone = ("    <!-- Generated by baslat.sh: drone with tilted camera, PX4 attaches via PX4_GZ_MODEL_NAME -->\n"
         "    <include>\n      <uri>model://x500_egik_kamera</uri>\n      <name>x500_mono_cam_0</name>\n"
         "      <pose>0 0 0 0 0 0</pose>\n    </include>\n  </world>")
open(dst, "w", encoding="utf-8").write(text.replace("  </world>", drone, 1))
EOF
link "$SIM_DIR/models/x500_egik_kamera" "models/x500_egik_kamera"
link "$SIM_DIR/worlds/renkli_duz_egik.sdf" "worlds/renkli_duz_egik.sdf"
export PX4_GZ_WORLD=renkli_duz_egik PX4_GZ_MODEL_NAME=x500_mono_cam_0
echo "Kamera (Camera Module 3) $TILT° aşağı eğik (dünya: renkli_duz_egik)"
export FOLLOW_CAMERA_PITCH_DEG="$TILT" FOLLOW_SIM_DIR="$SIM_DIR"

# Hook repair (PX4 wipes build/.../etc when ROMFS is regenerated)
HOOK="$PX4_DIR/build/px4_sitl_default/etc/init.d-posix/airframes/4010_gz_x500_mono_cam.post"
[[ -d "$(dirname "$HOOK")" && ! -e "$HOOK" ]] && ln -s "$SIM_DIR/px4_hook.post" "$HOOK"

cd "$PX4_DIR"
exec make px4_sitl gz_x500_mono_cam
